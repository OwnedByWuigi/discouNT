static const uint8_t *get_font(char c) {
    if (c >= 32 && c <= 126) return font_8x8[c - 32];
    return font_8x8[0];
}

static void vga_write_reg(uint16_t port, uint8_t index, uint8_t data) {
    outb(port, index);
    outb(port + 1, data);
}

void VgaInit(void) {
    outb(VGA_MISC_WRITE, 0xE3);
    
    vga_write_reg(VGA_SEQ_INDEX, 0, 0x03);
    vga_write_reg(VGA_SEQ_INDEX, 1, 0x01);
    vga_write_reg(VGA_SEQ_INDEX, 2, 0x0F);
    vga_write_reg(VGA_SEQ_INDEX, 3, 0x00);
    vga_write_reg(VGA_SEQ_INDEX, 4, 0x06);
    
    outb(VGA_CRTC_INDEX, 0x11);
    outb(VGA_CRTC_DATA, inb(VGA_CRTC_DATA) & 0x7F);
    
    uint8_t crtc[] = {0x5F,0x4F,0x50,0x82,0x54,0x80,0x0B,0x3E,
                      0x00,0x40,0x00,0x00,0x00,0x00,0x00,0x00,
                      0xEA,0x0C,0xDF,0x28,0x00,0xE7,0x04,0xE3,0xFF};
    for (int i = 0; i < 25; i++)
        vga_write_reg(VGA_CRTC_INDEX, i, crtc[i]);
    
    uint8_t gc[] = {0x00,0x00,0x00,0x00,0x00,0x00,0x05,0x0F,0xFF};
    for (int i = 0; i < 9; i++)
        vga_write_reg(VGA_GC_INDEX, i, gc[i]);
    
    inb(VGA_INSTAT_READ);
    for (int i = 0; i < 16; i++) {
        outb(VGA_AC_INDEX, i);
        outb(VGA_AC_WRITE, i);
    }
    outb(VGA_AC_INDEX, 0x10); outb(VGA_AC_WRITE, 0x41);
    outb(VGA_AC_INDEX, 0x11); outb(VGA_AC_WRITE, 0x00);
    outb(VGA_AC_INDEX, 0x12); outb(VGA_AC_WRITE, 0x0F);
    outb(VGA_AC_INDEX, 0x13); outb(VGA_AC_WRITE, 0x00);
    outb(VGA_AC_INDEX, 0x14); outb(VGA_AC_WRITE, 0x00);
    
    inb(VGA_INSTAT_READ);
    outb(VGA_AC_INDEX, 0x20);
}

void VgaClearScreen(uint8_t color) {
    // Set all planes for writing
    outb(VGA_SEQ_INDEX, 2);
    outb(VGA_SEQ_DATA, 0x0F);
    
    // Write mode 2 (fills with color)
    outb(VGA_GC_INDEX, 5);
    outb(VGA_GC_DATA, 2);
    
    // Full bit mask
    outb(VGA_GC_INDEX, 8);
    outb(VGA_GC_DATA, 0xFF);
    
    // Fill screen (38400 bytes per plane for 640x480)
    for (int i = 0; i < 38400; i++) {
        vga_memory[i] = color;
    }
    
    // Restore write mode 0
    outb(VGA_GC_INDEX, 5);
    outb(VGA_GC_DATA, 0);
}

void VgaPutPixel(int x, int y, uint8_t color) {
    if (x < 0 || x >= VGA_WIDTH || y < 0 || y >= VGA_HEIGHT) return;
    
    int offset = y * 80 + (x >> 3);
    int bit = 7 - (x & 7);
    uint8_t mask = 1 << bit;
    
    // Set write mode 0
    outb(VGA_GC_INDEX, 5);
    outb(VGA_GC_DATA, 0);
    
    // Enable all planes
    outb(VGA_SEQ_INDEX, 2);
    outb(VGA_SEQ_DATA, 0x0F);
    
    // Set bit mask
    outb(VGA_GC_INDEX, 8);
    outb(VGA_GC_DATA, mask);
    
    // Read to load latches, then write color
    uint8_t dummy = vga_memory[offset];
    (void)dummy;
    vga_memory[offset] = color;
    
    // Restore bit mask
    outb(VGA_GC_INDEX, 8);
    outb(VGA_GC_DATA, 0xFF);
}

void VgaDrawChar(int x, int y, char c, uint8_t fg, uint8_t bg) {
    const uint8_t *font = get_font(c);
    
    // First draw the background for the entire 8x8 cell
    for (int row = 0; row < 8; row++) {
        int py = y + row;
        if (py < 0 || py >= VGA_HEIGHT) continue;
        
        int row_start = py * 80;
        int start_byte = row_start + (x >> 3);
        int end_byte = row_start + ((x + 7) >> 3);
        
        if (start_byte == end_byte) {
            // All 8 pixels in one byte
            int start_bit = x & 7;
            uint8_t mask = 0xFF >> start_bit;
            if (start_bit > 0) mask &= 0xFF << (8 - start_bit - 8);
            else mask = 0xFF;
            
            outb(VGA_GC_INDEX, 5); outb(VGA_GC_DATA, 0);
            outb(VGA_SEQ_INDEX, 2); outb(VGA_SEQ_DATA, 0x0F);
            outb(VGA_GC_INDEX, 8); outb(VGA_GC_DATA, mask);
            uint8_t dummy = vga_memory[start_byte]; (void)dummy;
            vga_memory[start_byte] = bg;
        } else {
            // First byte (partial)
            int start_bit = x & 7;
            uint8_t mask = 0xFF >> start_bit;
            
            outb(VGA_GC_INDEX, 5); outb(VGA_GC_DATA, 0);
            outb(VGA_SEQ_INDEX, 2); outb(VGA_SEQ_DATA, 0x0F);
            outb(VGA_GC_INDEX, 8); outb(VGA_GC_DATA, mask);
            uint8_t dummy = vga_memory[start_byte]; (void)dummy;
            vga_memory[start_byte] = bg;
            
            // Second byte (partial)
            int remaining = 7 - (7 - start_bit);
            mask = 0xFF << (8 - remaining);
            
            outb(VGA_GC_INDEX, 8); outb(VGA_GC_DATA, mask);
            dummy = vga_memory[end_byte]; (void)dummy;
            vga_memory[end_byte] = bg;
        }
    }
    
    // Now draw the foreground character
    for (int row = 0; row < 8; row++) {
        uint8_t bits = font[row];
        int py = y + row;
        if (py < 0 || py >= VGA_HEIGHT) continue;
        
        for (int col = 0; col < 8; col++) {
            // MSB of font row = leftmost pixel
            if (bits & (0x80 >> col)) {
                VgaPutPixel(x + col, py, fg);
            }
        }
    }
    
    // Restore
    outb(VGA_GC_INDEX, 8);
    outb(VGA_GC_DATA, 0xFF);
}

void VgaDrawString(int x, int y, const char *str, uint8_t fg, uint8_t bg) {
    int cur_x = x;
    int cur_y = y;
    
    while (*str) {
        if (*str == '\n') {
            cur_x = x;
            cur_y += 10;
        } else {
            VgaDrawChar(cur_x, cur_y, *str, fg, bg);
            cur_x += 8;
            
            if (cur_x + 8 > VGA_WIDTH) {
                cur_x = x;
                cur_y += 10;
            }
        }
        str++;
        if (cur_y + 10 > VGA_HEIGHT) break;
    }
}

void VgaDrawRect(int x, int y, int w, int h, uint8_t color) {
    for (int i = 0; i < w; i++) {
        VgaPutPixel(x + i, y, color);
        VgaPutPixel(x + i, y + h - 1, color);
    }
    for (int i = 0; i < h; i++) {
        VgaPutPixel(x, y + i, color);
        VgaPutPixel(x + w - 1, y + i, color);
    }
}

void VgaFillRect(int x, int y, int w, int h, uint8_t color) {
    if (x < 0) { w += x; x = 0; }
    if (y < 0) { h += y; y = 0; }
    if (x + w > VGA_WIDTH) w = VGA_WIDTH - x;
    if (y + h > VGA_HEIGHT) h = VGA_HEIGHT - y;
    if (w <= 0 || h <= 0) return;
    
    outb(VGA_SEQ_INDEX, 2); outb(VGA_SEQ_DATA, 0x0F);
    outb(VGA_GC_INDEX, 5); outb(VGA_GC_DATA, 2);
    outb(VGA_GC_INDEX, 8); outb(VGA_GC_DATA, 0xFF);
    
    int start_bit = x & 7;
    int end_bit = (x + w - 1) & 7;
    
    for (int row = 0; row < h; row++) {
        int py = y + row;
        int start_byte = py * 80 + (x >> 3);
        int end_byte = py * 80 + ((x + w - 1) >> 3);
        
        if (start_byte == end_byte) {
            uint8_t mask = ((0xFF >> start_bit) & (0xFF << (7 - end_bit)));
            outb(VGA_GC_INDEX, 5); outb(VGA_GC_DATA, 0);
            outb(VGA_GC_INDEX, 8); outb(VGA_GC_DATA, mask);
            uint8_t dummy = vga_memory[start_byte]; (void)dummy;
            vga_memory[start_byte] = color;
        } else {
            if (start_bit != 0) {
                uint8_t mask = 0xFF >> start_bit;
                outb(VGA_GC_INDEX, 5); outb(VGA_GC_DATA, 0);
                outb(VGA_GC_INDEX, 8); outb(VGA_GC_DATA, mask);
                uint8_t dummy = vga_memory[start_byte]; (void)dummy;
                vga_memory[start_byte] = color;
                start_byte++;
            }
            
            outb(VGA_GC_INDEX, 5); outb(VGA_GC_DATA, 2);
            outb(VGA_GC_INDEX, 8); outb(VGA_GC_DATA, 0xFF);
            for (int b = start_byte; b < end_byte; b++) {
                vga_memory[b] = color;
            }
            
            if (end_bit != 7) {
                uint8_t mask = 0xFF << (7 - end_bit);
                outb(VGA_GC_INDEX, 5); outb(VGA_GC_DATA, 0);
                outb(VGA_GC_INDEX, 8); outb(VGA_GC_DATA, mask);
                uint8_t dummy = vga_memory[end_byte]; (void)dummy;
                vga_memory[end_byte] = color;
            }
        }
    }
    
    outb(VGA_GC_INDEX, 5); outb(VGA_GC_DATA, 0);
    outb(VGA_GC_INDEX, 8); outb(VGA_GC_DATA, 0xFF);
}

void VgaDrawLine(int x1, int y1, int x2, int y2, uint8_t color) {
    int dx = x2 - x1;
    int dy = y2 - y1;
    
    if (dx < 0) dx = -dx;
    if (dy < 0) dy = -dy;
    
    int sx = x1 < x2 ? 1 : -1;
    int sy = y1 < y2 ? 1 : -1;
    int err = (dx > dy ? dx : -dy) / 2;
    
    while (1) {
        VgaPutPixel(x1, y1, color);
        if (x1 == x2 && y1 == y2) break;
        int e2 = err;
        if (e2 > -dx) { err -= dy; x1 += sx; }
        if (e2 < dy)  { err += dx; y1 += sy; }
    }
}

