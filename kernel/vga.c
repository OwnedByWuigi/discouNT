static const uint8_t *get_font(char c) {
    if (c >= 32 && c <= 126) return font[c - 32];
    return font[0];
}

void VgaInit(void) {
    outb(0x3C2, 0xE3);
    outb(0x3C4, 0x00); outb(0x3C5, 0x03);
    outb(0x3C4, 0x01); outb(0x3C5, 0x01);
    outb(0x3C4, 0x02); outb(0x3C5, 0x0F);
    outb(0x3C4, 0x03); outb(0x3C5, 0x00);
    outb(0x3C4, 0x04); outb(0x3C5, 0x06);
    outb(0x3D4, 0x11); outb(0x3D5, inb(0x3D5) & 0x7F);
    uint8_t c[] = {0x5F,0x4F,0x50,0x82,0x54,0x80,0x0B,0x3E,0x00,0x40,0x00,0x00,0x00,0x00,0x00,0x00,0xEA,0x0C,0xDF,0x28,0x00,0xE7,0x04,0xE3,0xFF};
    for (int i = 0; i < 25; i++) { outb(0x3D4, i); outb(0x3D5, c[i]); }
    uint8_t g[] = {0x00,0x00,0x00,0x00,0x00,0x00,0x05,0x0F,0xFF};
    for (int i = 0; i < 9; i++) { outb(0x3CE, i); outb(0x3CF, g[i]); }
    inb(0x3DA);
    for (int i = 0; i < 16; i++) { outb(0x3C0, i); outb(0x3C0, i); }
    outb(0x3C0, 0x10); outb(0x3C0, 0x41);
    outb(0x3C0, 0x11); outb(0x3C0, 0x00);
    outb(0x3C0, 0x12); outb(0x3C0, 0x0F);
    outb(0x3C0, 0x13); outb(0x3C0, 0x00);
    outb(0x3C0, 0x14); outb(0x3C0, 0x00);
    inb(0x3DA); outb(0x3C0, 0x20);
    
    for (int i = 0; i < 640*480; i++) back_buffer[i] = 0;
}

// Flush back buffer to VGA planar memory correctly
static void flush_buffer(void) {
    uint8_t *planes[4];
    uint8_t plane_data[4][38400]; // 38400 bytes per plane (640*480/8)
    
    // Clear plane data
    for (int p = 0; p < 4; p++)
        for (int i = 0; i < 38400; i++)
            plane_data[p][i] = 0;
    
    // Build plane data from back buffer
    for (int y = 0; y < 480; y++) {
        for (int x = 0; x < 640; x++) {
            uint8_t color = back_buffer[y * 640 + x] & 0x0F;
            int byte_offset = y * 80 + (x >> 3);
            int bit = 7 - (x & 7);
            
            if (color & 1) plane_data[0][byte_offset] |= (1 << bit);
            if (color & 2) plane_data[1][byte_offset] |= (1 << bit);
            if (color & 4) plane_data[2][byte_offset] |= (1 << bit);
            if (color & 8) plane_data[3][byte_offset] |= (1 << bit);
        }
    }
    
    // Write each plane to VGA memory
    outb(0x3C4, 2);
    for (int p = 0; p < 4; p++) {
        outb(0x3C5, 1 << p);
        for (int i = 0; i < 38400; i++) {
            vga_mem[i] = plane_data[p][i];
        }
    }
    outb(0x3C5, 0x0F);
}

void VgaClearScreen(uint8_t color) {
    for (int i = 0; i < 640*480; i++) back_buffer[i] = color;
    flush_buffer();
}

void VgaPutPixel(int x, int y, uint8_t color) {
    if (x < 0 || x >= 640 || y < 0 || y >= 480) return;
    back_buffer[y * 640 + x] = color;
}

void VgaFillRect(int x, int y, int w, int h, uint8_t color) {
    if (x < 0) { w += x; x = 0; }
    if (y < 0) { h += y; y = 0; }
    if (x + w > 640) w = 640 - x;
    if (y + h > 480) h = 480 - y;
    if (w <= 0 || h <= 0) return;
    
    for (int row = y; row < y + h; row++) {
        for (int col = x; col < x + w; col++) {
            back_buffer[row * 640 + col] = color;
        }
    }
}

void VgaDrawRect(int x, int y, int w, int h, uint8_t color) {
    VgaFillRect(x, y, w, 1, color);
    VgaFillRect(x, y + h - 1, w, 1, color);
    VgaFillRect(x, y, 1, h, color);
    VgaFillRect(x + w - 1, y, 1, h, color);
}

void VgaDrawChar(int x, int y, char c, uint8_t fg, uint8_t bg) {
    const uint8_t *glyph = get_font(c);
    
    for (int row = 0; row < 8; row++) {
        uint8_t bits = glyph[row];
        for (int col = 0; col < 8; col++) {
            int px = x + col;
            int py = y + row;
            if (px >= 0 && px < 640 && py >= 0 && py < 480) {
                if (bits & (0x80 >> col)) {
                    back_buffer[py * 640 + px] = fg;
                } else {
                    back_buffer[py * 640 + px] = bg;
                }
            }
        }
    }
}

void VgaDrawString(int x, int y, const char *str, uint8_t fg, uint8_t bg) {
    int cx = x, cy = y;
    
    while (*str) {
        if (*str == '\n') {
            cx = x; cy += 10;
        } else {
            VgaDrawChar(cx, cy, *str, fg, bg);
            cx += 8;
            if (cx + 8 > 640) { cx = x; cy += 10; }
        }
        str++;
        if (cy + 10 > 480) break;
    }
}

void VgaSwapBuffers(void) {
    flush_buffer();
}